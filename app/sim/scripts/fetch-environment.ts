/**
 * Pulls real surface-environment data for the Earth analog sites and writes data/site-environment.json.
 *
 *   npx tsx scripts/fetch-environment.ts
 *
 * Sources (all free, no key):
 *   - NASA POWER climatology API (MERRA-2 / CERES SYN1deg): 10 m wind speed, direction and max,
 *     all-sky surface albedo, 2 m temperature.          https://power.larc.nasa.gov/
 *   - ISRIC SoilGrids v2.0: topsoil (0–5 cm) sand/silt/clay → USDA texture class.
 *                                                        https://soilgrids.org/
 *   - Sun elevation: equinox noon elevation from latitude (90° − |lat|).
 *
 * Moon/Mars sites are listed with the datasets to use but no values: rock abundance (Diviner,
 * TES/THEMIS), shadow fraction (LOLA illumination) and Mars winds (Mars Climate Database) are
 * still to be pulled by the data team.
 */
import { readFileSync, writeFileSync } from 'node:fs';

const ROOT = new URL('../../../', import.meta.url);
const catalog = JSON.parse(readFileSync(new URL('data/catalog_manifest.json', ROOT), 'utf8'));
const kilbourne = JSON.parse(readFileSync(new URL('web/public/terrain/kilbourne-hole-v1/manifest.json', ROOT), 'utf8'));

interface EarthSite { id: string; name: string; lat: number; lon: number }
const earthSites: EarthSite[] = [
  { id: kilbourne.id, name: kilbourne.name, lat: kilbourne.center_wgs84.latitude, lon: kilbourne.center_wgs84.longitude },
];
for (const [id, s] of Object.entries<any>(catalog.sites)) {
  if (s.body !== 'earth') continue;
  const [w, south, e, n] = s.bbox;
  earthSites.push({ id, name: s.name, lat: (south + n) / 2, lon: (w + e) / 2 });
}

async function power(lat: number, lon: number) {
  const url =
    'https://power.larc.nasa.gov/api/temporal/climatology/point' +
    `?parameters=WS10M,WD10M,WS10M_MAX,ALLSKY_SRF_ALB,T2M&community=RE&latitude=${lat}&longitude=${lon}&format=JSON`;
  const r = await fetch(url);
  if (!r.ok) throw new Error(`POWER ${r.status}`);
  const p = (await r.json()).properties.parameter;
  return { ws: p.WS10M.ANN, wd: p.WD10M.ANN, wsMax: p.WS10M_MAX.ANN, albedo: p.ALLSKY_SRF_ALB.ANN, t2m: p.T2M.ANN };
}

async function soil(lat: number, lon: number) {
  const url =
    `https://rest.isric.org/soilgrids/v2.0/properties/query?lon=${lon}&lat=${lat}` +
    '&property=sand&property=silt&property=clay&depth=0-5cm&value=mean';
  const r = await fetch(url);
  if (!r.ok) throw new Error(`SoilGrids ${r.status}`);
  const pct: Record<string, number | null> = {};
  for (const l of (await r.json()).properties.layers) {
    const v = l.depths[0].values.mean;
    pct[l.name] = v == null ? null : v / l.unit_measure.d_factor;
  }
  return pct as { sand: number | null; silt: number | null; clay: number | null };
}

/** USDA soil texture triangle (percent sand/silt/clay). */
export function usdaTexture(sand: number, silt: number, clay: number): string {
  if (silt + 1.5 * clay < 15) return 'sand';
  if (silt + 1.5 * clay < 30) return 'loamy sand';
  if ((clay >= 7 && clay < 20 && sand > 52) || (clay < 7 && silt < 50)) return 'sandy loam';
  if (clay >= 7 && clay < 27 && silt >= 28 && silt < 50 && sand <= 52) return 'loam';
  if ((silt >= 50 && clay >= 12 && clay < 27) || (silt >= 50 && silt < 80 && clay < 12)) return 'silt loam';
  if (silt >= 80 && clay < 12) return 'silt';
  if (clay >= 20 && clay < 35 && silt < 28 && sand > 45) return 'sandy clay loam';
  if (clay >= 27 && clay < 40 && sand > 20 && sand <= 45) return 'clay loam';
  if (clay >= 27 && clay < 40 && sand <= 20) return 'silty clay loam';
  if (clay >= 35 && sand > 45) return 'sandy clay';
  if (clay >= 40 && silt >= 40) return 'silty clay';
  return 'clay';
}

const out: Record<string, unknown> = {
  _comment:
    'Generated by app/sim/scripts/fetch-environment.ts. Values merge into SiteTerrain via applyEnvironment(). ' +
    'wind = mean vector the air moves towards (x east, y north), m/s.',
  generatedAt: new Date().toISOString(),
  sites: {} as Record<string, unknown>,
};
const sites = out.sites as Record<string, unknown>;

for (const s of earthSites) {
  process.stdout.write(`${s.id} (${s.lat.toFixed(2)}, ${s.lon.toFixed(2)}) … `);
  const p = await power(s.lat, s.lon);
  let texture: string | undefined;
  let soilPct: Awaited<ReturnType<typeof soil>> | undefined;
  try {
    soilPct = await soil(s.lat, s.lon);
    if (soilPct.sand != null && soilPct.silt != null && soilPct.clay != null)
      texture = usdaTexture(soilPct.sand, soilPct.silt, soilPct.clay);
  } catch (err) {
    console.warn(`(soil unavailable: ${(err as Error).message})`);
  }
  const toward = ((p.wd + 180) * Math.PI) / 180; // WD10M is where wind comes FROM
  sites[s.id] = {
    name: s.name,
    location: { lat: s.lat, lon: s.lon },
    wind: { x: +(p.ws * Math.sin(toward)).toFixed(2), y: +(p.ws * Math.cos(toward)).toFixed(2) },
    windGustMps: +((p.wsMax - p.ws) / 4).toFixed(2),
    albedo: p.albedo,
    soilType: texture ?? null,
    soil_percent_0_5cm: soilPct ?? null,
    temperatureC: p.t2m,
    sunElevationDeg: +(90 - Math.abs(s.lat)).toFixed(1),
    sources: {
      wind: 'NASA POWER climatology (MERRA-2), WS10M/WD10M annual mean',
      windGustMps: 'NASA POWER WS10M_MAX; gust sigma approximated as (max − mean) / 4',
      albedo: 'NASA POWER ALLSKY_SRF_ALB (CERES SYN1deg) annual mean',
      soilType: 'ISRIC SoilGrids v2.0, 0–5 cm sand/silt/clay → USDA texture class',
      temperatureC: 'NASA POWER T2M annual mean',
      sunElevationDeg: 'equinox noon sun elevation from latitude',
    },
  };
  console.log(`wind ${p.ws} m/s from ${p.wd}°, albedo ${p.albedo}, soil ${texture ?? '?'}`);
}

for (const [id, s] of Object.entries<any>(catalog.sites)) {
  if (s.body === 'earth') continue;
  sites[id] = {
    name: s.name,
    body: s.body,
    todo: {
      rockAbundance: s.body === 'moon' ? 'LRO Diviner rock abundance (PDS Geosciences)' : 'TES/THEMIS thermal-inertia rock abundance or HiRISE rock counts',
      shadowFraction: s.body === 'moon' ? 'LOLA polar illumination maps (PDS)' : 'n/a',
      wind: s.body === 'mars' ? 'Mars Climate Database (LMD/ESA) at the site and landing season' : 'none (airless)',
      albedo: s.body === 'moon' ? 'Diviner / LROC WAC normal albedo' : 'TES albedo',
    },
  };
}

writeFileSync(new URL('../data/site-environment.json', import.meta.url), JSON.stringify(out, null, 2) + '\n');
console.log('→ data/site-environment.json');
